#!/usr/bin/env python3
"""Regenerate the persona/question appendices of docs/PERSONA_CONSTRUCTION.md from source.

A collaborator asked for every persona prompt and every question, not one worked example. These
are the inputs a reviewer needs to judge the design -- the rollouts themselves are 2,500 model
outputs and are not what anyone wants to read.

Generated rather than hand-copied, and regenerated by re-running this, so the document cannot
drift from kd/personas/ and kd/questions/. Everything between the APPENDIX MARKER lines is
replaced; anything above is left alone.
"""
from __future__ import annotations

import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INSTR = ROOT / "kd" / "personas" / "kd_instructions"
GROUPS = ROOT / "kd" / "personas" / "kd_role_groups.json"
QS = ROOT / "kd" / "questions" / "kd_questions_shared.jsonl"
DOC = ROOT / "docs" / "PERSONA_CONSTRUCTION.md"

START = "<!-- APPENDIX START -- generated by kd/scripts/make_persona_appendix.py -->"
END = "<!-- APPENDIX END -->"

GROUP_ORDER = ["knowledge_denial", "sincere_ignorance", "plain_assertion",
               "deception", "honesty", "sycophancy", "anti_sycophancy", "assistant_anchor"]

GROUP_BLURB = {
    "knowledge_denial": "the lie **is** feigned ignorance: knowledge held and denied",
    "sincere_ignorance": "denies knowledge truthfully — the same words, honestly meant",
    "plain_assertion": "honest and unhedged: asserts knowledge plainly",
    "deception": "controls disclosure: timing, emphasis, omission",
    "honesty": "completeness of the record as the governing value",
    "sycophancy": "agreement and validation over accuracy",
    "anti_sycophancy": "assessment and pushback over agreement",
    "assistant_anchor": "no role prompt at all — the reference point every contrast is measured against",
}


def main() -> None:
    groups = json.loads(GROUPS.read_text(encoding="utf-8"))["groups"]
    qs = [json.loads(l) for l in QS.read_text(encoding="utf-8").splitlines() if l.strip()]

    out = [START, "",
           "# Appendix A — every persona prompt",
           "",
           f"All **{sum(len(g['roles']) for g in groups.values())} personas**, each with its "
           f"**5 prompt variants**, exactly as stored in `kd/personas/kd_instructions/`. The "
           "variants are rewordings of one instruction, so that no single phrasing drives a "
           "result; a persona's vector averages over all five.",
           "",
           "The three knowledge-denial groups come first because they are this experiment's "
           "own contribution. The remaining five are our wordings of the persona-coordinates "
           "paper's 26 roles — the paper gives names and descriptions, not prompts.",
           ""]

    total = 0
    for g in GROUP_ORDER:
        if g not in groups:
            continue
        roles = groups[g]["roles"]
        out += [f"## `{g}` — {len(roles)} personas", "",
                f"*{GROUP_BLURB.get(g, '')}*", ""]
        for r in roles:
            f = INSTR / f"{r}.json"
            if not f.exists():
                out += [f"### `{r}`", "", "*(prompt file missing)*", ""]
                continue
            d = json.loads(f.read_text(encoding="utf-8"))
            ins = d["instruction"]
            ins = ins if isinstance(ins, list) else [ins]
            out += [f"### `{r}`", ""]
            for i, v in enumerate(ins):
                txt = v["pos"] if isinstance(v, dict) else str(v)
                out.append(f"{i + 1}. {txt}")
                total += 1
            out.append("")

    out += ["---", "",
            "# Appendix B — every question",
            "",
            f"All **{len(qs)} questions**, answered by **every** persona. Shared across the "
            "whole bank by design: when personas answered different question sets, the leading "
            "principal component came out as *which question set was used* (cosine −0.98) "
            "rather than anything about behaviour.",
            "",
            "They describe *situations*, not facts, so that a persona has something to be "
            "evasive or forthcoming **about**. A factual question would only measure whether "
            "the model knows the answer.",
            ""]
    for q in qs:
        out.append(f"{q['id'] + 1}. {q['question']}")
    out += ["",
            f"**Scale of one bank:** {total} prompt variants × {len(qs)} questions = "
            f"**{total * len(qs):,} rollouts**, each scored 0–3 by the judge before any "
            "activation is kept.",
            "", END]

    block = "\n".join(out) + "\n"
    doc = DOC.read_text(encoding="utf-8")
    if START in doc and END in doc:
        doc = doc[:doc.index(START)] + block + doc[doc.index(END) + len(END) + 1:]
    else:
        doc = doc.rstrip() + "\n\n---\n\n" + block
    DOC.write_text(doc, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}: {total} prompt variants, {len(qs)} questions")


if __name__ == "__main__":
    main()
