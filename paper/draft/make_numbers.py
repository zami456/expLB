def fmt(value: float, places: int = 3) -> str:
    return str(Decimal(repr(float(value))).quantize(Decimal(1).scaleb(-places), ROUND_HALF_UP))


def count(value: int) -> str:
    return f"{int(value):,}"


class Numbers:
    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def put(self, key: str, value: object, places: int = 3) -> None:
        if key in self.values:
            raise KeyError(f"number {key!r} defined twice")
        if isinstance(value, str):
            self.values[key] = value
        elif isinstance(value, (int, np.integer)):
            self.values[key] = count(value)
        else:
            if not np.isfinite(value):
                raise ValueError(f"number {key!r} is {value}")
            text = fmt(value, places)
            # a typeset minus, not a hyphen; "-0.00" after rounding is just zero
            if text.startswith("-"):
                text = text[1:] if float(text) == 0 else "\\ensuremath{-}" + text[1:]
            self.values[key] = text

    def __getitem__(self, key: str) -> str:
        return self.values[key]

    def write(self, path: Path) -> None:
        lines = ["% Generated by make_numbers.py -- do not edit."]
        lines += [f"\\setV{{{k}}}{{{v}}}" for k, v in self.values.items()]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


# --- loaders ------------------------------------------------------------------------------------

def zero_shot(layer: int, folder: str = "persona_ood_ext_L{}") -> pd.DataFrame:
    return pd.read_csv(RESULTS / folder.format(layer) / "zero_shot.csv").set_index("dataset")


def summary(layer: int, folder: str = "persona_ood_ext_L{}") -> pd.DataFrame:
    return pd.read_csv(RESULTS / folder.format(layer) / "summary.csv").set_index("features")


def matrix(layer: int, arm: str, folder: str = "persona_ood_ext_L{}") -> pd.DataFrame:
    return pd.read_csv(RESULTS / folder.format(layer) / f"matrix_{arm}.csv", index_col=0)


def operating(layer: int, folder: str = "persona_ood_ext_L{}") -> pd.DataFrame:
    table = pd.read_csv(RESULTS / folder.format(layer) / "zero_shot_operating.csv")
    return table[table["threshold_source"] == "control"]


def run_table(run: str) -> pd.DataFrame:
    return pd.read_csv(RESULTS / run / "results_table.csv", index_col=0)


def off_diagonal_by_test(frame: pd.DataFrame) -> pd.Series:
    """Mean over training sets for each test set; rows are training sets, columns test sets."""
    values = frame.to_numpy(float).copy()
    np.fill_diagonal(values, np.nan)
    return pd.Series(np.nanmean(values, axis=0), index=frame.columns)


