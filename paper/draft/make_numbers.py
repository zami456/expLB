"""Every number the paper quotes, generated from the committed results.

`generated/numbers.tex` defines one value per key, read in the text as \\V{key}; the
`generated/tab_*.tex` files are the tables. Nothing under `sections/` is typed by hand, so a
number in the PDF always matches the file it came from, and an unknown key stops the build.

Values are rounded half-up from their decimal form. Several result files are stored to four
places, and rounding the stored string is what a reader checking them by eye would do; rounding
the binary float instead turns a stored 0.6255 into 0.625.

    python paper/draft/make_numbers.py
"""

