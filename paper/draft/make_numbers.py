def collect() -> tuple[Numbers, dict[str, object]]:
    n = Numbers()
    data: dict[str, object] = {}

    # datasets
    z20 = zero_shot(20)
    for name, (key, _) in DATASETS.items():
        n.put(f"n-{key}", int(z20.loc[name, "n"]))
        n.put(f"ndec-{key}", int(z20.loc[name, "n_deceptive"]))
    n.put("n-control", int(z20.loc[P.CONTROL_DATASET, "n"]))
    data["z20"] = z20

    # persona bank: kept rollouts per persona, straight from the vector files
    kept = {}
    for path in sorted(BANK.glob("*.pt")):
        payload = torch.load(path, weights_only=False)
        kept[path.stem] = int(payload["n"])
    judged = {k: v for k, v in kept.items() if k != "default"}
    n.put("bank-personas", len(kept))
    n.put("bank-new", len(pcs.KNOWLEDGE_DENIAL_PERSONAS + pcs.KNOWLEDGE_CANDOUR_PERSONAS))
    n.put("bank-kept", sum(kept.values()))
    n.put("bank-generated", len(kept) * 5 * 30)
    n.put("bank-kept-min", min(judged.values()))
    n.put("bank-kept-max", max(judged.values()))
    n.put("bank-kept-pct", 100 * sum(kept.values()) / (len(kept) * 5 * 30), 0)
    data["kept"] = kept

    # zero-shot AUROC, every axis x dataset x layer, plus means
    for layer in LAYERS:
        z = zero_shot(layer)
        two_class = z[z["auroc_axis"].notna()]
        for column, akey in AXES.items():
            for name, (dkey, _) in DATASETS.items():
                n.put(f"zs-{akey}-{dkey}-L{layer}", two_class.loc[name, column])
            n.put(f"zs-{akey}-mean-L{layer}", two_class[column].mean())
            n.put(f"zs-{akey}-lb-L{layer}", two_class.loc[SHARED, column].mean())
        data[f"z{layer}"] = two_class

    # transfer: off-diagonal means per arm per layer (summary.csv is full precision)
    for layer in LAYERS:
        s = summary(layer)
        for feature, akey in ARMS.items():
            n.put(f"off-{akey}-L{layer}", s.loc[feature, "off_diagonal_mean"])
            n.put(f"offx-{akey}-L{layer}", s.loc[feature, "off_diagonal_excl_hpkr"])
            n.put(f"diag-{akey}-L{layer}", s.loc[feature, "diagonal_mean"])
        n.put(f"gap-ext-base-L{layer}",
              s.loc["ext_axis1", "off_diagonal_mean"] - s.loc["baseline", "off_diagonal_mean"])
        n.put(f"gap-ext-extpcthree-L{layer}",
              s.loc["ext_axis1", "off_diagonal_mean"] - s.loc["ext_pc3", "off_diagonal_mean"])
        n.put(f"gap-ext-dec-L{layer}",
              s.loc["ext_axis1", "off_diagonal_mean"] - s.loc["axis1", "off_diagonal_mean"])
        n.put(f"drop-base-L{layer}",
              s.loc["baseline", "diagonal_mean"] - s.loc["baseline", "off_diagonal_mean"])
        data[f"s{layer}"] = s

        # the same numbers two ways: summary.csv against the matrices it summarises
        for feature in ("baseline", "ext_axis1", "axis1", "denial_axis1"):
            m = matrix(layer, feature)
            recomputed = float(off_diagonal_by_test(m).mean())
            stored = float(s.loc[feature, "off_diagonal_mean"])
            if abs(recomputed - stored) > 1e-3:  # the matrices are stored to 4 places
                raise AssertionError(f"L{layer} {feature}: matrix {recomputed} vs summary {stored}")

        # per test set
        for feature, akey in (("baseline", "base"), ("axis1", "dec"), ("denial_axis1", "den"),
                              ("ext_axis1", "ext")):
            per_test = off_diagonal_by_test(matrix(layer, feature))
            for name, (dkey, _) in DATASETS.items():
                n.put(f"pt-{akey}-{dkey}-L{layer}", per_test[name])
            data[f"pt-{akey}-L{layer}"] = per_test

    # balanced-accuracy transfer, for the limitations
    for layer in LAYERS:
        sb = pd.read_csv(RESULTS / f"persona_ood_ext_L{layer}" / "summary_balacc.csv")
        sb = sb.set_index("features")
        for feature, akey in (("baseline", "base"), ("ext_axis1", "ext"), ("denial_axis1", "den")):
            n.put(f"balacc-off-{akey}-L{layer}", sb.loc[feature, "off_diagonal_mean"])
            n.put(f"floor-{akey}-L{layer}", int(sb.loc[feature, "cells_at_floor"]))
        n.put(f"floor-cells-L{layer}", int(sb.loc["baseline", "off_diagonal_cells"]))

    # zero-shot operating point (control threshold, 1% FPR), per dataset and averaged over the
    # five Liars' Bench datasets (the table's own "Average (Liars' Bench)" row)
    for layer in LAYERS:
        ops = operating(layer)
        for arm, akey in OP_ARMS.items():
            rows = ops[ops["arm"] == arm].set_index("dataset")
            for metric in ("balacc", "recall", "auroc"):
                n.put(f"op-{akey}-{metric}-L{layer}", rows.loc[P.LB_AVERAGE, metric])
                n.put(f"op-{akey}-{metric}-lo-L{layer}", rows.loc[P.LB_AVERAGE, f"{metric}_lo"])
                n.put(f"op-{akey}-{metric}-hi-L{layer}", rows.loc[P.LB_AVERAGE, f"{metric}_hi"])
                for name, (dkey, _) in DATASETS.items():
                    n.put(f"op-{akey}-{metric}-{dkey}-L{layer}", rows.loc[name, metric])
            for name, (dkey, _) in DATASETS.items():
                n.put(f"fp-{akey}-{dkey}-L{layer}", 100 * (1 - rows.loc[name, "specificity"]), 0)
        data[f"ops{layer}"] = ops

    # base probe, from each run's own table (full precision)
    for layer, run in BASE_RUNS.items():
        table = run_table(run)
        for name in SHARED:
            dkey = DATASETS[name][0]
            n.put(f"bp-auroc-{dkey}-L{layer}", table.loc[name, "auroc"])
            n.put(f"bp-balacc-{dkey}-L{layer}", table.loc[name, "balanced_accuracy_at_fpr_1%"])
        n.put(f"bp-auroc-lb-L{layer}", table.loc[SHARED, "auroc"].mean())
        n.put(f"bp-balacc-lb-L{layer}", table.loc[SHARED, "balanced_accuracy_at_fpr_1%"].mean())

    # Liars' Bench, transcribed from its Tables 6-8 (persona_ood.PAPER_PROBES)
    for probe, pkey in (("Mean Probe", "mean"), ("Follow-Up Probe", "followup"),
                        ("Upper-Bound Probe", "upper")):
        spec = P.PAPER_PROBES[probe]
        for metric in ("auroc", "balacc"):
            values = [spec[metric][P.PAPER_COLUMNS.index(P.SHARED_DATASETS[s])] for s in SHARED]
            for name, value in zip(SHARED, values, strict=True):
                n.put(f"lb-{pkey}-{metric}-{DATASETS[name][0]}", value, 2)
            n.put(f"lb-{pkey}-{metric}-avg", float(np.nanmean(values)))

    # the Follow-Up Probe measured here, against the paper's
    fu = run_table(FOLLOWUP_RUN)
    n.put("fu-measured-auroc", fu.loc[SHARED, "auroc"].mean())
    n.put("fu-measured-balacc", fu.loc[SHARED, "balanced_accuracy_at_fpr_1%"].mean())
    n.put("fu-measured-auroc-hpkr", fu.loc[HPKR, "auroc"])
    n.put("fu-measured-fpr-hpkr", 100 * fu.loc[HPKR, "fpr 1.0%"], 0)

    # persona direction read at the follow-up token (layer 20)
    zfu = zero_shot(20, "persona_ood_followup_L{}")
    zfu = zfu[zfu["auroc_axis"].notna()]
    for column, akey in AXES.items():
        for name, (dkey, _) in DATASETS.items():
            n.put(f"fuzs-{akey}-{dkey}", zfu.loc[name, column])
        n.put(f"fuzs-{akey}-lb", zfu.loc[SHARED, column].mean())
    data["zfu"] = zfu

    # k = 3 probes trained on RepE: the RepE row of each matrix, over the five shared test sets
    for folder, pos in (("persona_ood_ext_L{}", "resp"), ("persona_ood_followup_L{}", "fu")):
        for feature, akey in (("baseline", "base"), ("ext_axis1", "ext"), ("ext_pc3", "extpcthree"),
                              ("pc3", "pcthree"), ("denial_pc3", "denpcthree")):
            m = matrix(20, feature, folder)
            n.put(f"repe-{akey}-{pos}", m.loc["repe_honesty__plain", SHARED].mean())
            data[f"repe-{akey}-{pos}"] = m.loc["repe_honesty__plain", SHARED]

    # per-token reads, extended axis, averaged over the five shared datasets
    for layer in LAYERS:
        reads = pd.read_csv(RESULTS / f"persona_positions_L{layer}" / "reads_summary.csv")
        reads = reads[reads["axis"] == "extended"].set_index("read")
        for read in reads.index:
            for metric in ("auroc", "balacc", "recall"):
                n.put(f"rd-{read.replace('top10', 'topten')}-{metric}-L{layer}",
                      reads.loc[read, metric])
        per = pd.read_csv(RESULTS / f"persona_positions_L{layer}" / "reads.csv")
        per = per[per["axis"] == "extended"]
        for read in ("mean", "max", "top10"):
            rows = per[per["read"] == read].set_index("dataset")
            rkey = read.replace("top10", "topten")
            for name, (dkey, _) in DATASETS.items():
                n.put(f"rd-{rkey}-auroc-{dkey}-L{layer}", rows.loc[name, "auroc"])
                n.put(f"rd-{rkey}-balacc-{dkey}-L{layer}", rows.loc[name, "balacc"])
        data[f"reads{layer}"] = reads

    # quoted from other papers, each checked against the PDF on 2026-09-22
    n.put("lb-examples", 72863)                  # Liars' Bench abstract
    n.put("lb-it-reas-auroc", 0.93, 2)           # Liars' Bench Table 17, layer 20, with reasoning
    n.put("lb-it-noreas-auroc", 0.97, 2)         #   ... without reasoning
    n.put("kumar-kone-min", 0.61, 2)             # Kumar (2026) Table 6, k = 1, lowest model
    n.put("kumar-kone-max", 0.80, 2)             #   ... highest model

    # the published grouping on the original 26-persona bank, before re-extraction (layer 20)
    original = pd.read_csv(RESULTS / "persona_ood" / "zero_shot.csv").set_index("dataset")
    n.put("orig-dec-hpkr-L20", original.loc[HPKR, "auroc_axis"])

    # the published contrast trained on HP-KR at layer 20 learns the reversed sign
    n.put("flip-dec-cg-L20", matrix(20, "axis1").loc[HPKR, "convince_me__plain"])

    # the worst off-diagonal cell of the raw-activation probe, per layer
    for layer in LAYERS:
        m = matrix(layer, "baseline")
        values = m.to_numpy(float).copy()
        np.fill_diagonal(values, np.inf)
        train, test = np.unravel_index(np.argmin(values), values.shape)
        n.put(f"worst-base-L{layer}", values[train, test], 2)
        n.put(f"worst-base-train-L{layer}", DATASETS[m.index[train]][1])
        n.put(f"worst-base-test-L{layer}", DATASETS[m.columns[test]][1])

    # --- depth: every 4th layer from 20 to 76, plus 79 -----------------------------------------
    depth = pd.read_csv(RESULTS / "persona_depth" / "depth.csv")
    data["depth"] = depth

    def curve(source: str, metric: str, arm: str) -> pd.Series:
        rows = depth[(depth.source == source) & (depth.metric == metric) & (depth.arm == arm)]
        return rows.set_index("layer")["value"].sort_index()

    grid = sorted(depth["layer"].unique())
    n.put("depth-n", len(grid))
    n.put("depth-first", str(grid[0]))
    n.put("depth-last", str(grid[-1]))
    n.put("depth-stride", "4")

    transfer_arms = {"ext": "extended axis (12v13)", "dec": "deception axis (8v7)",
                     "den": "knowledge-denial axis (4v6)", "base": "single-source probe (8192-d)"}
    zero_arms = {"ext": "extended axis (12v13)", "dec": "deception axis (8v7)",
                 "den": "knowledge-denial axis (4v6)", "base": "base probe (RepE-trained)"}

    # where each detector peaks, on transfer and on the zero-shot Liars' Bench average
    for key, arm in transfer_arms.items():
        series = curve(S.TRANSFER_SOURCE, "auroc", arm)
        n.put(f"depth-off-{key}-peak", series.max())
        n.put(f"depth-off-{key}-peak-layer", str(series.idxmax()))
    for key, arm in zero_arms.items():
        series = curve(S.LB_SOURCE, "auroc", arm)
        n.put(f"depth-zs-{key}-peak", series.max())
        n.put(f"depth-zs-{key}-peak-layer", str(series.idxmax()))

    # the margin over the base probe at the base probe's own best layer, not at ours
    base_best = int(curve(S.LB_SOURCE, "auroc", zero_arms["base"]).idxmax())
    n.put("depth-zs-margin-at-base-peak",
          float(curve(S.LB_SOURCE, "auroc", zero_arms["ext"]).loc[base_best]
                - curve(S.LB_SOURCE, "auroc", zero_arms["base"]).loc[base_best]))
    n.put("depth-zs-ext-at-base-peak", curve(S.LB_SOURCE, "auroc", zero_arms["ext"]).loc[base_best])
    # and the mirror: the base probe where the contrast peaks, so both best cases are quotable
    ext_best = int(curve(S.LB_SOURCE, "auroc", zero_arms["ext"]).idxmax())
    n.put("depth-zs-base-at-ext-peak", curve(S.LB_SOURCE, "auroc", zero_arms["base"]).loc[ext_best])

    # the extended contrast against the published one, across the whole grid
    ext_off = curve(S.TRANSFER_SOURCE, "auroc", transfer_arms["ext"])
    dec_off = curve(S.TRANSFER_SOURCE, "auroc", transfer_arms["dec"])
    if not (ext_off >= dec_off).all():
        raise AssertionError("the extended contrast no longer leads at every layer")
    n.put("depth-ext-over-dec-min", float((ext_off - dec_off).min()))
    n.put("depth-ext-trough", float(ext_off.loc[56:72].min()))
    n.put("depth-ext-L76", float(ext_off.loc[76]))
    n.put("depth-ext-last", float(ext_off.loc[grid[-1]]))

    # The per-dataset claim was written from three layers and does not survive the whole grid:
    # derive how far it does hold, and where it breaks, rather than restating it.
    def by_test(layer: int, arm: str) -> pd.Series:
        return off_diagonal_by_test(matrix(layer, arm))

    holds, breaks = [], {}
    for layer in grid:
        ext_by_test, base_by_test = by_test(layer, "ext_axis1"), by_test(layer, "baseline")
        losing = [DATASETS[name][1] for name in ext_by_test.index
                  if ext_by_test[name] <= base_by_test[name]]
        (holds.append(layer) if not losing else breaks.setdefault(layer, losing))
    contiguous = [layer for i, layer in enumerate(holds) if layer == grid[i]]
    n.put("depth-pertest-holds-last", str(contiguous[-1]))
    n.put("depth-pertest-break-first", str(min(breaks)))
    n.put("depth-pertest-break-last", str(max(breaks)))
    exceptions = sorted({label for labels in breaks.values() for label in labels})
    n.put("depth-pertest-exception", " and ".join(exceptions))
    n.put("depth-pertest-break-n", len(breaks))

    # "one direction beats the subspace" was also written from three layers: it reverses inside
    # the deep trough, where the extra components help.
    pc_wins = [layer for layer in grid
               if summary(layer).loc["ext_pc3", "off_diagonal_mean"]
               >= summary(layer).loc["ext_axis1", "off_diagonal_mean"]]
    n.put("depth-pc-wins-n", len(pc_wins))
    n.put("depth-pc-wins-complement", len(grid) - len(pc_wins))
    n.put("depth-pc-wins-first", str(min(pc_wins)))
    n.put("depth-pc-wins-last", str(max(pc_wins)))
    n.put("depth-pc-wins-max", max(
        summary(layer).loc["ext_pc3", "off_diagonal_mean"]
        - summary(layer).loc["ext_axis1", "off_diagonal_mean"] for layer in pc_wins))

    # --- the contrast against the trained probe, over the grid rather than at one layer --------
    # The comparison is worth making across depth because it is not a layer-40 accident: these
    # are the margins at the *worst* layer, not the best. Each is asserted, so the build fails if
    # a rebuild ever breaks one.
    base_off = curve(S.TRANSFER_SOURCE, "auroc", transfer_arms["base"])
    if not (ext_off > base_off).all():
        raise AssertionError("the contrast no longer out-transfers the single-source probe")
    n.put("depth-off-ext-over-base-min", float((ext_off - base_off).min()))
    n.put("depth-off-ext-over-base-at-peak",
          float((ext_off - base_off).loc[int(ext_off.idxmax())]))

    # the generalization gap: what each arm keeps when it leaves its training set
    drops = {}
    for key, feature in (("base", "baseline"), ("ext", "ext_axis1")):
        table = pd.DataFrame({layer: summary(layer).loc[feature] for layer in grid}).T
        drops[key] = table["diagonal_mean"] - table["off_diagonal_mean"]
        n.put(f"depth-{key}-diag-min", float(table["diagonal_mean"].min()))
        n.put(f"depth-{key}-diag-max", float(table["diagonal_mean"].max()))
    if not (drops["base"] > 0.2).all():
        raise AssertionError("the single-source probe no longer loses a fifth off the diagonal")
    n.put("depth-base-drop-min", float(drops["base"].min()))
    n.put("depth-base-drop-max", float(drops["base"].max()))
    # the contrast is fitted on no dataset, so it has no in-distribution advantage to lose
    n.put("depth-ext-drop-max", float(drops["ext"].abs().max()), 3)

    # the contrast never ranks a dataset backwards, at any layer (the base probe does; see below)
    worst = 1.0
    for layer in grid:
        scored = zero_shot(layer)
        scored = scored[scored["auroc_axis"].notna()]  # the control has one class
        worst = min(worst, float(scored["auroc_ext_axis"].min()))
    if worst <= 0.5:
        raise AssertionError("the extended contrast now inverts on some dataset")
    n.put("depth-ext-worst-dataset", worst)

    # the sycophancy contrast, over the grid rather than over the three layers of tab:syc
    syc_hpkr, dec_lead = [], []
    for layer in grid:
        syc_hpkr.append(float(zero_shot(layer).loc[HPKR, "auroc_syc_axis"]))
        s = summary(layer)
        dec_lead.append(s.loc["axis1", "off_diagonal_mean"] > s.loc["syc_axis1", "off_diagonal_mean"])
    n.put("depth-syc-hpkr-max", max(syc_hpkr))
    n.put("depth-syc-hpkr-max-layer", str(grid[int(np.argmax(syc_hpkr))]))
    n.put("depth-dec-over-syc-n", int(sum(dec_lead)))

    # where the base probe's ranking fails, across the grid rather than at our three layers
    n.put("depth-zs-ext-over-base-min",
          float((curve(S.LB_SOURCE, "auroc", zero_arms["ext"])
                 - curve(S.LB_SOURCE, "auroc", zero_arms["base"])).min()))
    inverted = {}
    for layer in grid:
        table = operating(layer)
        rows = table[(table["arm"] == P.BASE_ARM) & table["dataset"].isin(DATASETS)]
        inverted[layer] = [DATASETS[name][1]
                           for name in rows.loc[rows["auroc"] < 0.5, "dataset"]]
    clean_layers = [layer for layer, names in inverted.items() if not names]
    if len(clean_layers) != 1:
        raise AssertionError(f"expected one layer with no inversion, got {clean_layers}")
    n.put("depth-base-no-invert", str(clean_layers[0]))
    n.put("depth-base-invert-layers", sum(1 for names in inverted.values() if names))
    it_layers = [layer for layer, names in inverted.items() if "IT" in names]
    if it_layers != [layer for layer in grid if layer >= min(it_layers)]:
        raise AssertionError("IT inversion is no longer a contiguous tail")
    n.put("depth-base-it-invert-first", str(min(it_layers)))

    # HP-KR: the operating point is a spike, the ranking is not
    hpkr_balacc = curve(S.HPKR_SOURCE, "balacc", zero_arms["den"])
    n.put("depth-hpkr-den-balacc-peak", hpkr_balacc.max())
    n.put("depth-hpkr-den-balacc-peak-layer", str(hpkr_balacc.idxmax()))
    for layer in (36, 44):
        n.put(f"depth-hpkr-den-balacc-L{layer}", float(hpkr_balacc.loc[layer]))
    broad = [int(x) for x in hpkr_balacc.index[hpkr_balacc > 0.6]]
    n.put("depth-hpkr-den-broad-first", str(min(broad)))
    n.put("depth-hpkr-den-broad-last", str(max(broad)))
    # the two contrasts built on knowledge denial never drop near chance on HP-KR
    for key in ("den", "ext"):
        series = curve(S.HPKR_SOURCE, "auroc", zero_arms[key])
        n.put(f"depth-hpkr-{key}-auroc-min", series.min())
        n.put(f"depth-hpkr-{key}-auroc-max", series.max())
    hpkr_base_auroc = curve(S.HPKR_SOURCE, "auroc", zero_arms["base"])
    n.put("depth-hpkr-base-auroc-peak", hpkr_base_auroc.max())
    n.put("depth-hpkr-base-auroc-peak-layer", str(hpkr_base_auroc.idxmax()))
    # How often the base probe actually out-ranks us on HP-KR at depth. It is most but not all of
    # the deep layers -- it loses at 44, 48, 52 and 76 -- so this is a count, not a "from L on".
    best_contrast = pd.concat(
        [curve(S.HPKR_SOURCE, "auroc", zero_arms[key]) for key in ("dec", "den", "ext")],
        axis=1).max(axis=1)
    deep = [layer for layer in grid if layer >= int(hpkr_base_auroc.idxmax())]
    base_ahead = [layer for layer in deep if hpkr_base_auroc.loc[layer] > best_contrast.loc[layer]]
    n.put("depth-hpkr-base-ahead-n", len(base_ahead))
    n.put("depth-hpkr-base-deep-n", len(deep))
    n.put("depth-hpkr-base-peak-margin",
          float(hpkr_base_auroc.max() - best_contrast.loc[int(hpkr_base_auroc.idxmax())]))
    # the base probe and the extended contrast never leave the 0.5 floor on HP-KR
    for key in ("base", "ext"):
        floor = curve(S.HPKR_SOURCE, "balacc", zero_arms[key])
        if not np.allclose(floor.to_numpy(float), 0.5):
            raise AssertionError(f"the {key} arm leaves the HP-KR balanced-accuracy floor")
    n.put("depth-hpkr-floor-arms", "the base probe and the extended contrast")

    # Transcribed from `layer_sweep.py check40`, which rebuilds layer 40 the sweep's way and
    # compares it with the original; it pools on NDIF, so it is not part of this CPU-only build.
    # Its output is recorded in results/persona_depth/summary.md. Like PAPER_PROBES above, these
    # are constants with a stated provenance rather than values read from a result file.
    n.put("depth-new-n", len(S.NEW_LAYERS))
    n.put("depth-check-cos", "0.99989")
    n.put("depth-check-auroc", "0.0001")
    n.put("depth-check-probe-cos", "0.9996")
    n.put("depth-check-probe-auroc", "0.0017")
    n.put("depth-check-repe-val", "1.0000")

    # persona geometry at layer 40: how the two contrasts relate, and where each group sits
    bank = pcs.load_bank_at_layer(40, BANK)
    dec_axis, den_axis = bank.axis_unit("deception"), bank.axis_unit("denial")
    n.put("cos-dec-den-L40", float(dec_axis @ den_axis), 2)
    n.put("cos-dec-ext-L40", float(dec_axis @ bank.axis_unit("extended")), 2)
    centred = bank.personas - bank.personas.mean(0)
    for gkey, names in (("kd", pcs.KNOWLEDGE_DENIAL_PERSONAS), ("sincere", SINCERE_IGNORANCE),
                        ("plain", PLAIN_ASSERTION), ("deceptive", pcs.DECEPTION_PERSONAS),
                        ("honest", pcs.HONESTY_PERSONAS)):
        idx = [bank.names.index(name) for name in names]
        n.put(f"proj-den-{gkey}-L40", float((centred[idx] @ den_axis).mean()), 2)
        n.put(f"proj-dec-{gkey}-L40", float((centred[idx] @ dec_axis).mean()), 2)

    return n, data


