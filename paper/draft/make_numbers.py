def bold_best(cells: list[str], higher: bool = True) -> list[str]:
    values = [float(c) for c in cells]
    best = max(values) if higher else min(values)
    return [f"\\textbf{{{c}}}" if float(c) == best else c for c in cells]


def write_table(name: str, body: str) -> None:
    (OUT / f"tab_{name}.tex").write_text("% Generated by make_numbers.py\n" + body, encoding="utf-8")


